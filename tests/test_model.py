"""Model checks against CAD geometry and MuJoCo's independent kinematics/forces."""
import mujoco
import numpy as np
import pytest

from wheellegged.model import (
    GROUND_MARGIN,
    SIDES,
    WHEEL_RADIUS,
    closure_error,
    ground_forces,
    leg_geometry,
    load_model,
    make_data,
    wheel_centers,
)


@pytest.fixture(scope="module", params=("reference", "hardware_2s"))
def profile(request):
    return request.param


@pytest.fixture(scope="module")
def model(profile):
    return load_model(profile=profile)


@pytest.mark.parametrize("angle", np.linspace(-0.30, 0.0, 13))
def test_analytic_closed_chain_matches_mujoco(model, angle):
    # Closed-form two-circle solution is checked with MuJoCo's body tree,
    # rather than reusing the analytic closure expression in the assertion.
    data = make_data(model, hip_angle=float(angle), pitch=0.04)
    assert closure_error(model, data) < 1e-9
    assert np.max(np.abs(wheel_centers(data)[:, 2] - WHEEL_RADIUS)) < 1e-10


def test_geometry_matches_independent_cad_and_reference_statics():
    # CAD W is [-2.890291062, -20.914475612, 75.65] mm before the documented
    # frame conversion. q=-.2 height is separately published by the upstream
    # constrained-static verification, not generated by this implementation.
    zero = leg_geometry(0.0)
    assert zero["dx"] == pytest.approx(0.002890291062, abs=1e-10)
    assert zero["height"] == pytest.approx(0.036414475612, abs=1e-10)
    assert leg_geometry(-0.2)["standing_height"] == pytest.approx(0.07439558000288844, abs=1e-9)
    assert leg_geometry(-0.3)["height"] > leg_geometry(0.0)["height"]
    assert leg_geometry(-0.2)["dheight_dq"] < 0


def test_impossible_assembly_is_rejected():
    with pytest.raises(ValueError, match="outside the four-bar"):
        leg_geometry(0.30)


def test_model_retains_free_base_closed_chains_and_safe_actuation(model, profile):
    assert model.nq == 15 and model.nv == 14 and model.nu == 4
    assert model.neq == 2
    assert model.joint("floating_base").type[0] == mujoco.mjtJoint.mjJNT_FREE
    for side in SIDES:
        assert model.actuator(f"{side}_servo").ctrlrange == pytest.approx([-0.30, 0.0])
        assert model.joint(f"{side}_hip").range == pytest.approx([-0.35, 0.025])
        hip_cap = 0.15 if profile == "reference" else 0.14709975
        voltage_cap = 7.4 if profile == "reference" else 3.7
        wheel_cap = 0.08 if profile == "reference" else 0.0588
        bias = 0.0001 if profile == "reference" else 0.00047746482927568597
        assert model.actuator(f"{side}_servo").forcerange == pytest.approx([-hip_cap, hip_cap])
        assert model.actuator(f"{side}_wheel_voltage").ctrlrange == pytest.approx([-voltage_cap, voltage_cap])
        assert model.actuator(f"{side}_wheel_voltage").forcerange == pytest.approx([-wheel_cap, wheel_cap])
        assert model.actuator(f"{side}_wheel_voltage").gainprm[0] == pytest.approx(0.01)
        assert model.actuator(f"{side}_wheel_voltage").biasprm[:3] == pytest.approx([0, 0, -bias])


def test_mass_and_principal_inertias_are_physical(model, profile):
    expected_mass = 0.336 if profile == "reference" else 0.3176493810131978
    assert np.sum(model.body_mass) == pytest.approx(expected_mass, abs=1e-10)
    massive = model.body_mass > 0
    inertias = model.body_inertia[massive]
    assert np.all(np.isfinite(inertias)) and np.all(inertias > 0)
    assert np.all(2 * np.max(inertias, axis=1) <= np.sum(inertias, axis=1) + 1e-14)


def test_ground_sensor_matches_solver_contact_pressures(model):
    data = make_data(model)
    independent = np.zeros(2)
    for contact_index, contact in enumerate(data.contact):
        names = {model.geom(int(geom)).name for geom in contact.geom}
        for side_index, side in enumerate(SIDES):
            if names == {"floor", f"{side}_tire_contact"}:
                contact_force = np.zeros(6)
                mujoco.mj_contactForce(model, data, contact_index, contact_force)
                independent[side_index] += contact_force[0]
    assert np.all(independent > 0)
    assert ground_forces(data) == pytest.approx(independent, abs=1e-10)


def test_self_collision_cannot_be_mistaken_for_landing(model):
    # Deliberately penetrate the wheel shell outside the safe operating range,
    # while lifting the entire assembly well above every world geom.
    data = make_data(model, hip_angle=0.10)
    data.joint("floating_base").qpos[2] += 0.15
    mujoco.mj_forward(model, data)
    assert any("outer_shell_contact" in model.geom(int(g)).name
               for c in data.contact for g in c.geom)
    assert ground_forces(data) == pytest.approx([0.0, 0.0], abs=1e-12)


@pytest.mark.parametrize("terrain", ("flat", "bridge", "step"))
def test_ground_margin_and_terrain_are_explicit(terrain, profile):
    model = load_model(terrain, profile=profile)
    assert model.geom("floor").margin[0] == pytest.approx(GROUND_MARGIN)
    for side in SIDES:
        assert model.geom(f"{side}_tire_contact").margin[0] == pytest.approx(GROUND_MARGIN)
    if terrain != "flat":
        obstacle = model.geom(f"terrain_{terrain}")
        assert obstacle.margin[0] == pytest.approx(GROUND_MARGIN)
        assert 2 * obstacle.size[2] == pytest.approx(0.006)
        assert obstacle.pos[2] - obstacle.size[2] == pytest.approx(0.0)


def test_imu_reports_chassis_orientation_and_finite_measurements(model):
    data = make_data(model, pitch=0.05)
    assert data.sensor("imu_orientation").data == pytest.approx(data.body("chassis").xquat)
    assert np.all(np.isfinite(data.sensor("imu_gyro").data))
    assert np.all(np.isfinite(data.sensor("imu_accelerometer").data))
